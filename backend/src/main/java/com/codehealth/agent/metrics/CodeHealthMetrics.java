package com.codehealth.agent.metrics;

import io.micrometer.core.instrument.Counter;
import io.micrometer.core.instrument.MeterRegistry;
import org.springframework.stereotype.Component;

/**
 *  Author: Kumar.Kunal
 *  Project: codeguardian-ai
 *  File: CodeHealthMetrics.java
 *  Date: October 31, 2026
 * Event counters exported to Prometheus. Rates (flaky rate, CI noise) are gauges in {@link MetricsService}.
 */
@Component
public class CodeHealthMetrics {

    private final Counter llmFallbacks;
    private final Counter automatedFixes;
    private final Counter proposals;

    public CodeHealthMetrics(MeterRegistry registry) {
        this.llmFallbacks = Counter.builder("codehealth.llm.fallback")
                .description("LLM calls that failed and fell back to the template generator")
                .register(registry);
        this.automatedFixes = Counter.builder("codehealth.fixes.automated")
                .description("LOW risk fixes approved by policy without a human")
                .register(registry);
        this.proposals = Counter.builder("codehealth.proposals.created")
                .description("Proposals generated by the agent")
                .register(registry);
    }

    public void llmFallback() {
        llmFallbacks.increment();
    }

    public void automatedFix() {
        automatedFixes.increment();
    }

    public void proposalCreated() {
        proposals.increment();
    }
}
